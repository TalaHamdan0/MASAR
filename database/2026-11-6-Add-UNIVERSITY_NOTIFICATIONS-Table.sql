CREATE TABLE UNIVERSITY_NOTIFICATIONS (
    NOTIFICATION_ID NUMBER GENERATED BY DEFAULT AS IDENTITY,
    USER_ID NUMBER NOT NULL,
    TITLE VARCHAR2(800) NOT NULL,
    MESSAGE VARCHAR2(4000) NOT NULL,
    NOTIFICATION_TYPE VARCHAR2(80) DEFAULT 'GENERAL' NOT NULL,
    IS_READ NUMBER(1) DEFAULT 0 NOT NULL,
    CREATED_AT TIMESTAMP(6) DEFAULT LOCALTIMESTAMP NOT NULL,
    READ_AT TIMESTAMP(6),
    RELATED_ENTITY_TYPE VARCHAR2(80),
    RELATED_ENTITY_ID NUMBER,

    CONSTRAINT PK_UNIV_NOTIF
        PRIMARY KEY (NOTIFICATION_ID),

    CONSTRAINT FK_UNIV_NOTIF_USER
        FOREIGN KEY (USER_ID)
        REFERENCES USERS(USER_ID),

    CONSTRAINT CK_UNIV_NOTIF_READ
        CHECK (IS_READ IN (0, 1))
);

CREATE INDEX IDX_UNIV_NOTIF_USER
ON UNIVERSITY_NOTIFICATIONS (
    USER_ID,
    IS_READ,
    CREATED_AT
);